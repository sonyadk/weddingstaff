book.addEventListener("click", event => {
  const button = event.target.closest("button[data-action]");
  if (!button || turning) return;

  switch (button.dataset.action) {
    case "next":
      goTo(current + 1);
      break;

    case "cover":
      goTo(0);
      break;

    case "card":
      openCard(Number(button.dataset.card));
      break;

    case "genre": {
      const sceneIndex = Number(button.dataset.scene);
      const scene = SCENES[sceneIndex];
      const position = ((genrePositions.get(sceneIndex) || 0) + 1) % scene.genres.length;
      const genreEl = document.getElementById(`genre-${sceneIndex}`);
      const nextGenre = scene.genres[position];
      genrePositions.set(sceneIndex, position);
      document.getElementById(`genre-counter-${sceneIndex}`).textContent =
        `Жанр ${position + 1} / ${scene.genres.length}`;
      if (reducedMotion.matches || !genreEl.animate) {
        genreEl.textContent = nextGenre;
      } else if (genreEl.dataset.animating !== "true") {
        genreEl.dataset.animating = "true";
        genreEl.animate([
          { opacity: 1, transform: "translateY(0) scale(1)" , filter: "blur(0)"},
          { opacity: 0, transform: "translateY(-9px) scale(.97)", filter: "blur(4px)" }
        ], { duration: 170, easing: "ease-in", fill: "forwards" }).finished.then(() => {
          genreEl.textContent = nextGenre;
          return genreEl.animate([
            { opacity: 0, transform: "translateY(10px) scale(.97)", filter: "blur(4px)" },
            { opacity: 1, transform: "translateY(0) scale(1)", filter: "blur(0)" }
          ], { duration: 330, easing: "cubic-bezier(.16,1,.3,1)", fill: "both" }).finished;
        }).catch(() => { genreEl.textContent = nextGenre; }).finally(() => {
          genreEl.dataset.animating = "false";
        });
      }
      const box = genreEl.closest(".genre-box");
      if (box && !reducedMotion.matches) {
        box.classList.remove("magic-pulse");
        void box.offsetWidth;
        box.classList.add("magic-pulse");
      }
      break;
    }

    case "fact": {
      const factIndex = Number(button.dataset.fact);
      revealedFacts.add(factIndex);
      document.getElementById(`fact-answer-${factIndex}`).hidden = false;
      button.setAttribute("aria-expanded", "true");
      button.textContent = "Ответ открыт";
      button.disabled = true;
      break;
    }
  }
});

/* =========================================================
   КЛАВИАТУРА
   Пробел на кнопке нажимает кнопку, а не листает книгу.
   ========================================================= */

document.addEventListener("keydown", event => {
  if (event.defaultPrevented || event.altKey || event.ctrlKey || event.metaKey) return;
  if (contentsDialog.open || cardDialog.open) return;

  const onControl = event.target.closest(
    "button, a, input, textarea, select, [contenteditable='true']"
  );

  if (event.key === " " && onControl) return;

  if (["ArrowRight", "PageDown", " "].includes(event.key)) {
    event.preventDefault();
    goTo(current + 1);
  } else if (["ArrowLeft", "PageUp"].includes(event.key)) {
    event.preventDefault();
    goTo(current - 1);
  } else if (event.key === "Home") {
    event.preventDefault();
    goTo(0);
  } else if (event.key === "End") {
    event.preventDefault();
    goTo(PAGES.length - 1);
  }
});

/* =========================================================
   СВАЙПЫ
   Вертикальная прокрутка длинной страницы не перелистывает её.
   ========================================================= */

let touchStart = null;

stage.addEventListener("touchstart", event => {
  if (event.touches.length !== 1 ||
      event.target.closest("button") ||
      turning || contentsDialog.open || cardDialog.open) {
    touchStart = null;
    return;
  }

  touchStart = {
    x: event.touches[0].clientX,
    y: event.touches[0].clientY
  };
}, { passive: true });

stage.addEventListener("touchend", event => {
  if (!touchStart || !event.changedTouches.length) return;

  const dx = event.changedTouches[0].clientX - touchStart.x;
  const dy = event.changedTouches[0].clientY - touchStart.y;
  touchStart = null;

  if (Math.abs(dx) > 75 && Math.abs(dx) > Math.abs(dy) * 1.8) {
    goTo(current + (dx < 0 ? 1 : -1));
  }
}, { passive: true });

stage.addEventListener("touchcancel", () => {
  touchStart = null;
}, { passive: true });

