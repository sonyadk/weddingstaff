function updateInterface(announce = true) {
  pageElements.forEach((element, i) => {
    const active = i === current;
    element.classList.toggle("active", active);
    element.setAttribute("aria-hidden", String(!active));
    element.inert = !active;
  });

  const page = PAGES[current];
  document.getElementById("counter").textContent =
    `${String(current + 1).padStart(2, "0")} / ${String(PAGES.length).padStart(2, "0")}`;

  document.getElementById("progressFill").style.width =
    `${((current + 1) / PAGES.length) * 100}%`;

  document.getElementById("chapterLabel").textContent = page.title;
  prevBtn.disabled = current === 0;
  nextBtn.disabled = current === PAGES.length - 1;

  const chapterStart = [...CHAPTERS]
    .reverse()
    .find(chapter => chapter.index <= current);

  document.querySelectorAll("#toc button").forEach(button => {
    const isCurrent = chapterStart &&
      Number(button.dataset.jump) === chapterStart.index;
    if (isCurrent) button.setAttribute("aria-current", "page");
    else button.removeAttribute("aria-current");
  });

  if (announce) {
    document.getElementById("announcement").textContent =
      `Страница ${current + 1} из ${PAGES.length}. ${page.title}.`;
  }
}

async function goTo(target, animate = true) {
  if (turning || contentsDialog.open || cardDialog.open) return;
  target = Math.max(0, Math.min(PAGES.length - 1, target));
  if (target === current) return;

  const outgoing = pageElements[current];
  const incoming = pageElements[target];
  const forward = target > current;
  turning = true;
  current = target;
  incoming.querySelector(".copy").scrollTop = 0;

  if (!animate || reducedMotion.matches) {
    updateInterface();
    turning = false;
    return;
  }

  updateInterface();
  // Оставляем предыдущий разворот видимым поверх нового на время перелистывания.
  outgoing.style.visibility = "visible";
  outgoing.style.pointerEvents = "none";
  outgoing.style.zIndex = "6";
  incoming.style.zIndex = "5";
  const direction = forward ? 1 : -1;
  const mobile = mobileView.matches;
  const duration = mobile ? 260 : 360;
  const portal = document.createElement("div");
  portal.className = "portal-flash";
  portal.setAttribute("aria-hidden", "true");
  book.append(portal);

  const outFrames = mobile ? [
    { opacity: 1, transform: "translateX(0) scale(1)" },
    { opacity: 0, transform: `translateX(${-direction * 24}px) scale(.985)` }
  ] : [
    { opacity: 1, transform: "translateX(0) rotateY(0deg) scale(1)", filter: "brightness(1)" },
    { opacity: .78, transform: `translateX(${-direction * 16}px) rotateY(${-direction * 3}deg) scale(.992)`, filter: "brightness(.82)", offset: .58 },
    { opacity: 0, transform: `translateX(${-direction * 34}px) rotateY(${-direction * 7}deg) scale(.985)`, filter: "brightness(.7)" }
  ];
  const inFrames = mobile ? [
    { opacity: 0, transform: `translateX(${direction * 28}px) scale(.985)` },
    { opacity: 1, transform: "translateX(0) scale(1)" }
  ] : [
    { opacity: 0, transform: `translateX(${direction * 32}px) rotateY(${direction * 8}deg) scale(.985)`, filter: "brightness(.75)" },
    { opacity: .86, transform: `translateX(${direction * 12}px) rotateY(${direction * 3}deg) scale(.994)`, filter: "brightness(.9)", offset: .52 },
    { opacity: 1, transform: "translateX(0) rotateY(0deg) scale(1)", filter: "brightness(1)" }
  ];

  try {
    const animations = [
      outgoing.animate(outFrames, { duration: duration * .78, easing: "cubic-bezier(.55,.05,.7,.25)", fill: "both" }),
      incoming.animate(inFrames, { duration, easing: "cubic-bezier(.16,1,.3,1)", fill: "both" }),
      portal.animate([
        { opacity: 0, transform: "translate(-50%,-50%) scale(.35) rotate(-18deg)" },
        { opacity: .92, transform: "translate(-50%,-50%) scale(1) rotate(0deg)", offset: .36 },
        { opacity: 0, transform: "translate(-50%,-50%) scale(1.55) rotate(18deg)" }
      ], { duration, easing: "ease-out", fill: "both" })
    ];
    await Promise.all(animations.map(animation => animation.finished.catch(() => undefined)));
    animations.forEach(animation => animation.cancel());
  } catch (error) {
    // The presentation remains usable if a browser interrupts an animation.
  } finally {
    portal.remove();
    outgoing.style.visibility = "";
    outgoing.style.pointerEvents = "";
    outgoing.style.zIndex = "";
    incoming.style.zIndex = "";
    updateInterface(false);
    turning = false;
  }

  if (outgoing.contains(document.activeElement)) {
    const heading = incoming.querySelector("h1, h2");
    if (heading) {
      heading.tabIndex = -1;
      heading.focus({ preventScroll: true });
    }
  }
}

